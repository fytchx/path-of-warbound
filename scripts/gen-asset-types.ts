import { readFileSync, writeFileSync } from 'node:fs';

interface ManifestAsset {
  id: string;
  file: string;
  category: string;
  w: number;
  h: number;
  alpha: boolean;
  tags: string[];
  note: string;
}

interface Manifest {
  version: string;
  count: number;
  assets: ManifestAsset[];
}

const manifest = JSON.parse(readFileSync('assets/manifest.json', 'utf8')) as Manifest;
const categories = [...new Set(manifest.assets.map((a) => a.category))].sort();

const rows = manifest.assets
  .map(
    (a) =>
      `  ${JSON.stringify(a.id)}: { file: ${JSON.stringify(a.file)}, category: ${JSON.stringify(a.category)}, w: ${a.w}, h: ${a.h}, alpha: ${a.alpha} },`,
  )
  .join('\n');

const byCategory = categories
  .map(
    (c) =>
      `  ${JSON.stringify(c)}: [${manifest.assets
        .filter((a) => a.category === c)
        .map((a) => JSON.stringify(a.id))
        .join(', ')}],`,
  )
  .join('\n');

const out = `// GENERATED by scripts/gen-asset-types.ts from assets/manifest.json — do not edit by hand.
// The manifest is the single source of truth: art is referenced only by AssetId.

export const MANIFEST_VERSION = ${JSON.stringify(manifest.version)};
export const MANIFEST_COUNT = ${manifest.count};

export type AssetCategory =
${categories.map((c) => `  | ${JSON.stringify(c)}`).join('\n')};

export type AssetId =
${manifest.assets.map((a) => `  | ${JSON.stringify(a.id)}`).join('\n')};

export interface AssetMeta {
  file: string;
  category: AssetCategory;
  w: number;
  h: number;
  alpha: boolean;
}

export const ASSETS: Record<AssetId, AssetMeta> = {
${rows}
};

export const ASSET_IDS_BY_CATEGORY: Record<AssetCategory, AssetId[]> = {
${byCategory}
};

export const ALL_ASSET_IDS = Object.keys(ASSETS) as AssetId[];

export function isAssetId(value: string): value is AssetId {
  return Object.prototype.hasOwnProperty.call(ASSETS, value);
}
`;

writeFileSync('src/assets/assetIds.ts', out);
console.log(`assetIds.ts written: ${manifest.assets.length} assets in ${categories.length} categories`);
